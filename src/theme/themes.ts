/** The themes in the order every picker lists them: light ones first, then dark ones, Astra's own at the head of each. */
export const appThemeList: readonly AppTheme[] = [...lightThemeIds, ...darkThemeIds].map((id) => appThemes[id]);

export function isAppThemeId(value: unknown): value is AppThemeId {
  return typeof value === "string" && Object.hasOwn(appThemes, value);
}
