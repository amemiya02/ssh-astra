import type { ITheme } from "@xterm/xterm";

/**
 * The app's themes. One theme paints the whole window: the chrome (`ui`) and the
 * Terminal (`terminal`) together. Literal colours live in theme and Terminal palette definitions.
 * `src/index.css` derives every token from the `--ui-*` variables that `applyTheme` writes from here.
 */

export const lightThemeIds = ["light", "githubLight", "catppuccinLatte", "solarizedLight"] as const;
export const darkThemeIds = [
  "dark",
  "tokyoNight",
  "oneDark",
  "nord",
  "catppuccinMocha",
  "dracula",
  "gruvboxDark",
  "solarizedDark",
  "githubDark",
] as const;

export type LightThemeId = (typeof lightThemeIds)[number];
export type DarkThemeId = (typeof darkThemeIds)[number];
/** `light` and `dark` are Astra Light and Astra Dark; their ids predate the other themes and stay valid in saved settings. */
export type AppThemeId = LightThemeId | DarkThemeId;

export interface ThemeUi {
  /** The window behind everything: tab strip, status bar, gutters. */
  ground: string;
  /** The nav rail and Host list column. */
  sidebar: string;
  /** Raised work panels (File panel, cards). */
  surface: string;
  /** Menus, dialogs and popovers. */
  raised: string;
  foreground: string;
  mutedForeground: string;
  border: string;
  primary: string;
  primaryForeground: string;
  success: string;
  warning: string;
  destructive: string;
}

/** The names of the 16 ANSI colours xterm takes. */
export const ansiColorKeys = [
  "black",
  "red",
  "green",
  "yellow",
  "blue",
  "magenta",
  "cyan",
  "white",
  "brightBlack",
  "brightRed",
  "brightGreen",
  "brightYellow",
  "brightBlue",
  "brightMagenta",
  "brightCyan",
  "brightWhite",
] as const;

/** A complete xterm palette: every colour set, the 16 ANSI ones included. */
export type TerminalPalette = ITheme &
  Record<(typeof ansiColorKeys)[number] | "background" | "foreground" | "cursor" | "cursorAccent" | "selectionBackground", string>;

export interface AppTheme {
  id: AppThemeId;
  /** A proper noun, shown untranslated. */
  name: string;
  appearance: "light" | "dark";
  ui: ThemeUi;
  /** Full 16 ANSI colours plus background, foreground, cursor and selection. */
  terminal: TerminalPalette;
}

